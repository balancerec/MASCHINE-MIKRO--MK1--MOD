const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'control-studio/dist/calibration.js'),'utf8'),context);
const create=()=>context.window.MikroCalibration.createEncoderTracker();
const fixture=path.join(__dirname,'tests/fixtures/encoder-ten-right.json');
const packets=JSON.parse(fs.readFileSync(fixture,'utf8')).packets;
const tracker=create();
const observed=packets.map(packet=>tracker.read(packet));
assert.equal(observed.filter(x=>x.delta===1).length,10);
assert.equal(observed.at(-1).total,10);
assert.equal(observed.filter(x=>x.pushChanged&&x.pressed).length,2);
assert.equal(observed.filter(x=>x.pushChanged&&!x.pressed).length,2);
const packet=(pos,pressed=false)=>[1,0,pressed?8:0,0,0,pos];
const left=create();left.read(packet(0));
assert.equal(left.read(packet(15)).delta,-1);
assert.equal(left.read(packet(14)).total,-2);
assert.equal(left.read(packet(6)).ambiguous,true);
assert.equal(left.read(packet(5)).total,-3);
left.reset();assert.equal(left.read(packet(12)).delta,0);
assert.equal(left.read([32,...Array(64).fill(0)]),null);
assert.equal(left.read([1,0]),null);
assert.equal(left.read([1,0,0,0,0,NaN]),null);
assert.equal(left.read(packet(11)).delta,-1);
console.log('Encoder: real 10-detent capture, two clicks, wrap, reverse, ambiguous jump, reset and invalid packets passed.');
